#!/usr/bin/env python3
"""Geometry data for an interactive view of the round-2 general-rate diagnostic.

Visualisation only. It computes no new hypothesis column, no rate and no
verdict. Every momentum-space and velocity-space number about the rate
(dominant points, characters, xi_*, v_*, rho, s_0, K_*, labels) is read from
reports/2026-11-12--general-ir-rate-round2.json. What is reconstructed here
is the lattice geometry each walk is defined on, from the same constructors
the diagnostic used (imported read-only):

- the lattice generated by the steps (P.lattice_data) and its steps;
- the Brillouin zone of that lattice (Voronoi cell of 2 pi L*), by half-space
  intersection;
- when H3 holds, the primitive dual vector u along xi_* (from the stored
  dual-basis ratios) and the lines R u + 2 pi L* clipped to the zone, which
  is exactly the set of momenta whose character is trivial on L cap u^perp;
- Bob's vertex V = v_* + 2 rho xi_*/|xi_*| (region rule), checked to be a
  step of maximal norm; P.choose_vertex is re-run and its distance to that V
  recorded. Rows where no maximal step satisfies the rule are flagged.

Floating point throughout; for display only.

Usage (from the repo root):
  python3 -B scripts/build_ir_rate_round2_geometry.py
writes reports/figures/2026-11-12--ir-rate-round2-geometry.json and the page
reports/figures/2026-11-12--ir-rate-round2-geometry.html from the template
reports/figures/ir-rate-round2-geometry.template.html.
"""
import hashlib
import itertools
import json
import sys
from fractions import Fraction
from math import gcd
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import diagnose_general_ir_rate_round2 as R2  # noqa: E402  (imports P, Zs read-only)

P = R2.P
Zs = R2.Zs
SRC = ROOT / "reports/2026-11-12--general-ir-rate-round2.json"
OUT_JSON = ROOT / "reports/figures/2026-11-12--ir-rate-round2-geometry.json"
TEMPLATE = ROOT / "reports/figures/ir-rate-round2-geometry.template.html"
OUT_HTML = ROOT / "reports/figures/2026-11-12--ir-rate-round2-geometry.html"
TOL = 1e-9


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def dual_vectors(D, d, r):
    """2 pi L* vectors with integer coordinates in [-r, r], excluding 0."""
    out = []
    for m in itertools.product(range(-r, r + 1), repeat=d):
        if any(m):
            out.append(2 * np.pi * D @ np.array(m, float))
    return np.array(out)


def voronoi_cell(G, d):
    """Vertices of {p : g.p <= |g|^2/2 for g in G}."""
    b = 0.5 * np.einsum("ij,ij->i", G, G)
    verts = []
    for idx in itertools.combinations(range(len(G)), d):
        A = G[list(idx)]
        if abs(np.linalg.det(A)) < 1e-9:
            continue
        p = np.linalg.solve(A, b[list(idx)])
        if np.all(G @ p <= b + 1e-7):
            if not any(np.linalg.norm(p - q) < 1e-6 for q in verts):
                verts.append(p)
    V = np.array(verts)
    if d == 2:
        ang = np.arctan2(V[:, 1], V[:, 0])
        V = V[np.argsort(ang)]
    return V, b


def fold(p, G, b):
    """Representative of p modulo 2 pi L* inside the Voronoi cell."""
    p = np.array(p, float)
    for _ in range(200):
        viol = G @ p - b
        i = int(np.argmax(viol))
        if viol[i] <= 1e-9:
            return p
        p = p - G[i]
    return p


def clip_line(g, uh, G, b):
    """Segment of {g + t uh} inside the cell, or None."""
    lo, hi = -1e9, 1e9
    for h, bh in zip(G, b):
        a, c = h @ uh, bh - h @ g
        if abs(a) < 1e-12:
            if c < -1e-9:
                return None
            continue
        t = c / a
        if a > 0:
            hi = min(hi, t)
        else:
            lo = max(lo, t)
    if hi - lo <= 1e-9:
        return None
    return [(g + lo * uh).tolist(), (g + hi * uh).tolist()]


def hull2(pts):
    pts = sorted(map(tuple, pts))
    if len(pts) <= 2:
        return [list(p) for p in pts]

    def cross(o, a, b_):
        return (a[0] - o[0]) * (b_[1] - o[1]) - (a[1] - o[1]) * (b_[0] - o[0])
    lower, upper = [], []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return [list(p) for p in lower[:-1] + upper[:-1]]


def regime(h, dom):
    h3, h4 = h.get("H3"), h.get("H4prime")
    fails = [k for k, v in h.items() if v is False]
    if not fails:
        return "theorem"
    if h3 is False and h4 is True:
        return "h3"
    if h3 is True and h4 is False:
        return "r1" if any(x["trivial_character"] for x in dom) else "r2"
    return "h3h4"


def primitive_u(ratios, D):
    q = [Fraction(x) for x in ratios]
    den = 1
    for x in q:
        den = den * x.denominator // gcd(den, x.denominator)
    ints = [int(x * den) for x in q]
    g = 0
    for a in ints:
        g = gcd(g, abs(a))
    ints = [a // g for a in ints]
    return D @ np.array(ints, float), ints


def build(row, walk):
    wid, name, builder, phase = walk
    M, zs, gens = builder()
    terms = P.laurent_terms(M, zs)
    basis, steps = P.lattice_data(terms, gens)
    d = len(gens)
    sym = P.Symbol(terms, steps)
    B = np.array([[float(x) for x in b_] for b_ in basis]).T
    D = np.linalg.inv(B).T                       # dual basis (columns), k.x in Z
    G = dual_vectors(D, d, 2)
    cell, bb = voronoi_cell(G, d)
    step_pts = np.array([[float(x) for x in v] for v in steps.values()])
    Zs.FALLBACK.clear()
    V = np.array([float(x) for x in P.choose_vertex(steps, d, sym)])

    xi = np.array(row["xi_star"])
    xih = xi / np.linalg.norm(xi)
    vstar = np.array(row["v_star"])
    rho = row["rho"]
    # Region rule of the round-2 charter: B - A is the ball of radius 2 rho at V
    # and v_* = V - 2 rho xi_*/|xi_*|, so the stored data fix V; take V from the
    # data and check it is a maximal step.
    V_data = vstar + 2 * rho * xih
    norms = np.linalg.norm(step_pts, axis=1)
    near = np.linalg.norm(step_pts - V_data, axis=1)
    j = int(np.argmin(near))
    n_max = int(np.sum(np.abs(norms - norms.max()) < 1e-9))
    minimiser_gap = float(near[j])
    consistent = bool(minimiser_gap < 1e-6 and abs(norms[j] - norms.max()) < 1e-9
                      and abs(norms[j] - row["h"]) < 1e-9)
    V_check = float(np.linalg.norm(V - V_data))
    if consistent:
        V = step_pts[j]
    # else: the stored (xi_*, v_*) do not satisfy v_* + 2 rho xi_*/|xi_*| = V for
    # any maximal step; keep the rebuilt V for display and flag the row.

    dom = []
    for x in row["dominant_points"]:
        k = np.array(x["k"])
        dom.append(dict(k=k.tolist(), k_folded=fold(k, G, bb).tolist(),
                        is_zero=x["is_zero"], trivial=x["trivial_character"],
                        gap_ratio=x["gap_ratio"]))

    lines, u_info = [], None
    if row["hypotheses"].get("H3"):
        u, ints = primitive_u(row["xi_dual_ratios"], D)
        if u @ xi < 0:
            u, ints = -u, [-a for a in ints]
        uh = u / np.linalg.norm(u)
        u_info = dict(u=u.tolist(), u_dual_coords=ints, abs_u=float(np.linalg.norm(u)))
        seen = []
        for g in np.vstack([np.zeros(d), dual_vectors(D, d, 3)]):
            perp = g - (g @ uh) * uh
            if any(np.linalg.norm(perp - s) < 1e-6 for s in seen):
                continue
            seg = clip_line(g, uh, G, bb)
            if seg is not None:
                seen.append(perp)
                lines.append(seg)

    hyp = row["hypotheses"]
    out = dict(
        id=wid, name=name, d=d, s=row["s"], label=row["label"],
        regime=regime(hyp, row["dominant_points"]),
        hypotheses=hyp, lattice_cubic=row["lattice_isometric_to_Zd"],
        basis=B.T.tolist(), covol=float(abs(np.linalg.det(B))),
        steps=step_pts.tolist(),
        conv_steps=hull2(step_pts) if d == 2 else step_pts.tolist(),
        bz=cell.tolist(), dominant=dom, trivial_lines=lines, u=u_info,
        c_IR=row["node"]["c_IR"], s0=row["s0"], h=row["h"], rho=rho,
        K_star=row["K_star"], xi_star=xi.tolist(), v_star=vstar.tolist(),
        V=V.tolist(), V_rebuilt_minus_data=V_check, maximal_steps=n_max,
        minimiser_consistent=consistent, minimiser_gap=minimiser_gap,
        fast_modes=row["fast_modes_along_n"], no_rate_axis=row["no_rate_axis"])
    return out


def main():
    src = json.loads(SRC.read_text())
    rows = {r["id"]: r for r in src["walks"]}
    walks = []
    for walk in R2.walk_list():
        r = build(rows[walk[0]], walk)
        print(f"{r['id']:4s} {r['regime']:7s} BZ vertices {len(r['bz']):3d} "
              f"lines {len(r['trivial_lines']):2d} maximal steps {r['maximal_steps']:2d} "
              f"minimiser gap {r['minimiser_gap']:.1e}"
              + ("" if r["minimiser_consistent"] else "  INCONSISTENT"))
        walks.append(r)
    meta = dict(source=str(SRC.relative_to(ROOT)), source_sha256=sha(SRC),
                script=str(Path(__file__).resolve().relative_to(ROOT)),
                script_sha256=sha(__file__),
                imported=dict(round2=sha(R2.__file__), polyhedra=sha(P.__file__),
                              zonotopes=sha(Zs.__file__)),
                numpy=np.__version__,
                nature="visualisation of a floating-point diagnostic; no verdicts")
    data = dict(meta=meta, walks=walks)
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(data, indent=1))
    html = TEMPLATE.read_text().replace("/*__DATA__*/null", json.dumps(data))
    OUT_HTML.write_text(html)
    print(f"wrote {OUT_JSON.relative_to(ROOT)} and {OUT_HTML.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

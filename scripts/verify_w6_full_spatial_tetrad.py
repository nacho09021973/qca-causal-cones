"""Exact rank certificate for theory/W6_FULL_SPATIAL_TETRAD_GATE.md."""

import sympy as sp


def main():
    g = sp.symbols("g", nonzero=True)
    E0 = sp.diag(1, -1, 1)
    D = sp.Matrix([[1,0,0],[1,1,0],[1,1,1]])
    assert D.det() == 1

    zs = sp.symbols("z11 z12 z13 z21 z22 z23 z31 z32 z33")
    Z = sp.Matrix(3, 3, zs)
    dE = -2*g*Z*D

    # Rank of linear map Z -> dE.
    cols_E = []
    for z in zs:
        cols_E.append(sp.Matrix([sp.diff(dE[i,j], z) for i in range(3) for j in range(3)]))
    ME = sp.Matrix.hstack(*cols_E)
    assert ME.rank() == 9
    print("[PASS] full spatial tetrad tangent rank = 9")

    dh = sp.simplify(E0.T*dE + dE.T*E0)
    comps = [(0,0),(1,1),(2,2),(0,1),(0,2),(1,2)]
    cols_h=[]
    for z in zs:
        cols_h.append(sp.Matrix([sp.diff(dh[i,j], z) for (i,j) in comps]))
    Mh = sp.Matrix.hstack(*cols_h)
    assert Mh.rank() == 6
    assert len(Mh.nullspace()) == 3
    print("[PASS] induced spatial metric tangent rank = 6 with kernel dimension 3")

    # Kernel form: E0^T dE antisymmetric.
    a12,a13,a23 = sp.symbols("a12 a13 a23")
    A = sp.Matrix([[0,a12,a13],[-a12,0,a23],[-a13,-a23,0]])
    dEker = E0*A
    dhker = sp.simplify(E0.T*dEker + dEker.T*E0)
    assert dhker == sp.zeros(3)
    print("[PASS] kernel is generated by antisymmetric frame directions")

    # Same kernel written as infinitesimal internal rotations dE = Omega E0.
    Omega = sp.simplify(E0*A*E0)
    assert sp.simplify(Omega.T + Omega) == sp.zeros(3)
    assert sp.simplify(Omega*E0 - dEker) == sp.zeros(3)
    print("[PASS] kernel equals infinitesimal SO(3)-type frame rotations at linear order")

    print("\nVERDICT: W6 spans a generic spatial tetrad and all six spatial metric perturbations.")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Fetch arXiv titles and abstracts for the forward-citation list.

Input : investigaciones/2026-11-17-c0-causal-body-prior-art/citas_hacia_adelante.csv
        (written by scripts/prior_art_forward_citations.py)
Output: investigaciones/2026-11-17-c0-causal-body-prior-art/resumenes_citas.md
        literal arXiv metadata (id, title, authors, abstract), one block per
        paper, for manual screening. No filtering or judgement here.
Uses the arXiv export API (batches of 20, 3 s between calls). Sends only
arXiv identifiers. Usage (repo root): python3 scripts/prior_art_fetch_abstracts.py
"""
import csv
import pathlib
import time
import urllib.request
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
D = ROOT / "investigaciones/2026-11-17-c0-causal-body-prior-art"
NS = {"a": "http://www.w3.org/2005/Atom"}
UA = {"User-Agent": "prior-art-citation-check/1.0"}

rows = [r for r in csv.DictReader((D / "citas_hacia_adelante.csv").open()) if r["arxiv"]]
ids = [r["arxiv"] for r in rows]
cites = {r["arxiv"]: r["cites"] for r in rows}
out = ["# arXiv abstracts of forward citations (literal, unscreened)", "",
       "Generated by scripts/prior_art_fetch_abstracts.py from citas_hacia_adelante.csv.", ""]
for i in range(0, len(ids), 20):
    batch = ids[i:i + 20]
    url = "http://export.arxiv.org/api/query?max_results=20&id_list=" + ",".join(batch)
    req = urllib.request.Request(url, headers=UA)
    root = ET.fromstring(urllib.request.urlopen(req, timeout=60).read())
    for e in root.findall("a:entry", NS):
        aid = e.find("a:id", NS).text.rsplit("/abs/", 1)[-1]
        base = aid.rsplit("v", 1)[0] if "v" in aid.split("/")[-1] else aid
        title = " ".join(e.find("a:title", NS).text.split())
        authors = ", ".join(a.find("a:name", NS).text for a in e.findall("a:author", NS))
        summ = " ".join(e.find("a:summary", NS).text.split())
        out += [f"## {base} — {title}", "", f"Authors: {authors}",
                f"Cites: {cites.get(base, '?')}", "", summ, ""]
    time.sleep(3)
(D / "resumenes_citas.md").write_text("\n".join(out))
print(len([l for l in out if l.startswith("## ")]), "abstracts of", len(ids))

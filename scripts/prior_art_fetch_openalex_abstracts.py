#!/usr/bin/env python3
"""Fetch OpenAlex abstracts for the non-arXiv forward citations.

Input : investigaciones/2026-11-17-c0-causal-body-prior-art/citas_hacia_adelante.csv
Output: investigaciones/2026-11-17-c0-causal-body-prior-art/resumenes_citas_no_arxiv.md
        literal OpenAlex metadata per work (title, year, DOI, venue, open-access
        URL, abstract rebuilt verbatim from OpenAlex's inverted index, or
        "no abstract in OpenAlex"). No filtering or judgement here.
Sends only OpenAlex work IDs. Usage (repo root):
  python3 scripts/prior_art_fetch_openalex_abstracts.py
"""
import csv
import json
import pathlib
import time
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
D = ROOT / "investigaciones/2026-11-17-c0-causal-body-prior-art"
UA = {"User-Agent": "prior-art-citation-check/1.0"}


def abstract(inv):
    if not inv:
        return None
    pos = {}
    for word, idxs in inv.items():
        for i in idxs:
            pos[i] = word
    return " ".join(pos[i] for i in sorted(pos))


rows = [r for r in csv.DictReader((D / "citas_hacia_adelante.csv").open()) if not r["arxiv"]]
out = ["# OpenAlex abstracts of non-arXiv forward citations (literal, unscreened)", "",
       "Generated by scripts/prior_art_fetch_openalex_abstracts.py.", ""]
for r in rows:
    url = (f"https://api.openalex.org/works/{r['openalex']}"
           "?select=id,display_name,publication_year,doi,primary_location,open_access,"
           "abstract_inverted_index,type")
    w = json.loads(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read())
    venue = ((w.get("primary_location") or {}).get("source") or {}).get("display_name") or ""
    oa = (w.get("open_access") or {}).get("oa_url") or ""
    out += [f"## {r['openalex']} — {w.get('display_name') or ''}", "",
            f"Year: {w.get('publication_year')}; type: {w.get('type')}; DOI: {w.get('doi') or ''}",
            f"Venue: {venue}; OA URL: {oa}; cites: {r['cites']}", "",
            abstract(w.get("abstract_inverted_index")) or "(no abstract in OpenAlex)", ""]
    time.sleep(0.3)
(D / "resumenes_citas_no_arxiv.md").write_text("\n".join(out))
print(len(rows), "works")

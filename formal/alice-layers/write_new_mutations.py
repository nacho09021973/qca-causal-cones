"""Generate permanent mutation inventory for the new independent comparator."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
entries = []

def add(name, before, after, path='AliceComparator/NewChallenge.lean',
        expected=r'(?i)AliceComparator/NewSolution\.lean[^\n]*error:[^\n]*type mismatch'):
    entries.append(dict(nombre=name, fichero=path, antes=before, despues=after, espera=expected))

add('claim derivative factor', 'HasDerivAt positiveSquare (2 * max z 0) z', 'HasDerivAt positiveSquare (3 * max z 0) z')
add('claim smoothness', 'def PositiveSquareC1 : Prop := ContDiff ℝ 1 positiveSquare', 'def PositiveSquareC1 : Prop := ContDiff ℝ 2 positiveSquare')
add('claim section derivative factor', '(-4*y * max (δ-y^2-x^2) 0) y', '(-5*y * max (δ-y^2-x^2) 0) y')
add('claim boundary derivative', 'deriv (fun t : ℝ => positiveSquare (δ-t^2-x^2)) y = 0', 'deriv (fun t : ℝ => positiveSquare (δ-t^2-x^2)) y = 1')
add('claim section smoothness', 'ContDiff ℝ 1 (psiSlice δ τ x : ℝ → ℂ)', 'ContDiff ℝ 2 (psiSlice δ τ x : ℝ → ℂ)')
add('claim Fourier swap frequencies', '= psi δ (shiftedTau τ u v)', '= psi δ (shiftedTau τ v u)')
add('claim Fourier inequality factor', '∫ y : ℝ, ‖deriv (psiSlice δ τ x : ℝ → ℂ) y‖', '2 * ∫ y : ℝ, ‖deriv (psiSlice δ τ x : ℝ → ℂ) y‖')
add('definition positive square', 'def positiveSquare (z : ℝ) : ℝ := (max z 0)^2', 'def positiveSquare (z : ℝ) : ℝ := (max z 1)^2')
add('definition shift sign', '![τ 0 - 2 * Real.pi * u, τ 1 - 2 * Real.pi * v]', '![τ 0 + 2 * Real.pi * u, τ 1 - 2 * Real.pi * v]')
add('definition profile exponent', 'def psiIntegrand (δ : ℝ) (τ σ : Tangent) : ℂ :=\n  (((max (δ - ∑ i, σ i ^ 2) 0)^2 : ℝ) : ℂ)', 'def psiIntegrand (δ : ℝ) (τ σ : Tangent) : ℂ :=\n  (((max (δ - ∑ i, σ i ^ 2) 0)^3 : ℝ) : ℂ)')
add('definition integral', 'def psi (δ : ℝ) (τ : Tangent) : ℂ := ∫ σ : Tangent, psiIntegrand δ τ σ', 'def psi (δ : ℝ) (τ : Tangent) : ℂ := 2 * ∫ σ : Tangent, psiIntegrand δ τ σ')
add('definition slice', 'toFun y := psiIntegrand δ τ ![y, x]', 'toFun y := psiIntegrand δ τ ![x, y]')
add('axiom guard sorry', ':= @AliceLayers.psi_double_fourier', ':= sorry',
    path='AliceComparator/NewSolution.lean',
    expected=r'(?s)AliceComparator/NewAxioms\.lean.*non-standard axioms: \[sorryAx\]')

if __name__ == '__main__':
    lines = ['# Generated by write_new_mutations.py.', 'timeout = 180', '']
    for entry in entries:
        lines.append('[[mutacion]]')
        lines.extend(f'{key} = {json.dumps(value, ensure_ascii=False)}' for key, value in entry.items())
        lines.append('')
    (HERE/'new_mutations.toml').write_text('\n'.join(lines)+'\n')

"""Genera el inventario permanente de alteraciones del comparador (sin ejecutar Lean)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
entries = []


def change(name, before, after, file='AliceComparator/Challenge.lean', pattern=r'(?i)AliceComparator/Solution\.lean[^\n]*error:[^\n]*type mismatch'):
    entries.append(dict(nombre=name, fichero=file, antes=before, despues=after, espera=pattern))


change('enunciado: fase central signo',
       'phase N η x = uncenteredPhase η x - centerCoordinate N * ∑ i, η i',
       'phase N η x = uncenteredPhase η x + centerCoordinate N * ∑ i, η i')
change('enunciado: condicion transversal 0 a 1',
       '(_h : ∑ i, η i = 0), phase N η x', '(_h : ∑ i, η i = 1), phase N η x')
change('enunciado: desigualdad finita factor 2',
       '‖ ≤ ∑ x ∈ s, |w x|', '‖ ≤ 2 * ∑ x ∈ s, |w x|')
change('enunciado: perfil 64 a 65', '(64/n^2) * (δ', '(65/n^2) * (δ')
change('enunciado: prefactor 16 a 17', '(16*Real.pi/Real.sqrt 3) * φ', '(17*Real.pi/Real.sqrt 3) * φ')
change('enunciado: norma de marco factor 2',
       '(normalFrequency η)^2 + ∑ i, (transverseCoordinates η i)^2 = ∑ i, η i ^ 2',
       '(normalFrequency η)^2 + ∑ i, (transverseCoordinates η i)^2 = 2 * ∑ i, η i ^ 2')
change('enunciado: soporte conjuncion adicional',
       'def SupportFaithfulnessClaim : Prop := SupportFaithfulness',
       'def SupportFaithfulnessClaim : Prop := SupportFaithfulness ∧ True')
change('definicion: norma cuadrada factor 2',
       'def sqNorm (x : Lattice) : ℝ := ∑ i, (x i : ℝ)^2',
       'def sqNorm (x : Lattice) : ℝ := 2 * ∑ i, (x i : ℝ)^2')
change('definicion: frecuencia normal sqrt5',
       'def normalFrequency (η : Frequency) : ℝ := (∑ i, η i) / Real.sqrt 3',
       'def normalFrequency (η : Frequency) : ℝ := (∑ i, η i) / Real.sqrt 5')
change('definicion: centro N/8sqrt3',
       'def centerCoordinate (N : ℕ) : ℝ := (N : ℝ) / (4 * Real.sqrt 3)',
       'def centerCoordinate (N : ℕ) : ℝ := (N : ℝ) / (8 * Real.sqrt 3)')
change('definicion: fase con centro sumado',
       '∑ i, η i * ((x i : ℝ) - centerCoordinate N)',
       '∑ i, η i * ((x i : ℝ) + centerCoordinate N)')
change('definicion: fase sin centro duplicada',
       'def uncenteredPhase (η : Frequency) (x : Lattice) : ℝ := ∑ i, η i * (x i : ℝ)',
       'def uncenteredPhase (η : Frequency) (x : Lattice) : ℝ := 2 * ∑ i, η i * (x i : ℝ)')
change('definicion: caja ampliada',
       'Fintype.piFinset fun _ => Finset.Icc (-(N : ℤ)) (N : ℤ)',
       'Fintype.piFinset fun _ => Finset.Icc (-(2*(N : ℤ))) (2*(N : ℤ))')
change('definicion: esfera 16 a 15',
       '(latticeBox N).filter fun x => 16 * sqNorm x ≤ (N : ℝ)^2',
       '(latticeBox N).filter fun x => 15 * sqNorm x ≤ (N : ℝ)^2')
change('definicion: marco sqrt2 a sqrt5',
       '![(η 0-η 1)/Real.sqrt 2, (η 0+η 1-2*η 2)/Real.sqrt 6]',
       '![(η 0-η 1)/Real.sqrt 5, (η 0+η 1-2*η 2)/Real.sqrt 6]')
change('definicion: soporte umbral 17',
       'x ∈ aliceSites N ↔ 16 * sqNorm x ≤ (N : ℝ)^2',
       'x ∈ aliceSites N ↔ 17 * sqNorm x ≤ (N : ℝ)^2')
change('axiomas: prueba sustituida por sorry',
       ':= @AliceLayers.phase_sub_center', ':= sorry', file='AliceComparator/Solution.lean',
       pattern=r'(?s)AliceComparator/Axioms\.lean.*non-standard axioms: \[sorryAx\]')

if __name__ == '__main__':
    content = ['# Generated by write_mutations.py; source remains permanent.', 'timeout = 180', '']
    for entry in entries:
        content.append('[[mutacion]]')
        content.extend(f'{key} = {json.dumps(value, ensure_ascii=False)}' for key, value in entry.items())
        content.append('')
    with (HERE/'mutaciones.toml').open('x') as stream:
        stream.write('\n'.join(content)+'\n')
